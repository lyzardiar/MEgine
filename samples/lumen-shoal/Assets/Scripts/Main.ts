const STYLE_NAMES = ['REALISTIC / 写实', 'LOW-POLY / 低多边形', 'PIXEL / 像素'];

let elapsed = 0;
let stage = 0;
let autoplay = true;
let stageTimer = 0;
let styleTarget = 0;
let lastEnvExposure = -999;

// Smoothed animated values.
const cur = {
  water: [0, 0, 0, 0] as Vec4,
  ground: [0, 0, 0, 0] as Vec4,
  sky: [0, 0, 0, 0] as Vec4,
  style: 0,
  exposure: 0,
  camRadius: 210,
  camHeight: 74,
  camAngle: 0.6,
};

const byName: Record<string, number> = {};
const stylable: number[] = [];
let lastEnvTex = '';
let pollenId = -1;
let cameraId = -1;
let envId = -1;
let ui: Record<string, number> = {};

function lerp(a: number, b: number, k: number): number { return a + (b - a) * k; }

function lookAt(eye: number[], target: number[]): number[] {
  const dx = target[0] - eye[0], dy = target[1] - eye[1], dz = target[2] - eye[2];
  const len = Math.hypot(dx, dy, dz) || 1;
  const nx = dx / len, ny = dy / len, nz = dz / len;
  const yaw = Math.atan2(-nx, -nz);
  const horiz = Math.hypot(nx, nz) || 1e-6;
  const pitch = Math.atan2(ny, horiz);
  // q = qyaw(Y) * qpitch(X); forward = q * -Z
  const cy = Math.cos(yaw / 2), sy = Math.sin(yaw / 2);
  const cp = Math.cos(pitch / 2), sp = Math.sin(pitch / 2);
  // multiply (cy,0,sy,0)wxyz by (cp,sp,0,0)
  const w = cy * cp, x = cy * sp, y = sy * cp, z = -sy * sp;
  return [x, y, z, w];
}

function setComponent(entity: number, component: string, value: unknown): void {
  engine.pushCommandJson(JSON.stringify({ op: 'setComponent', entity, component, value }));
}

function pushMaterial(entity: number, reveal: Vec4): void {
  setComponent(entity, 'MaterialPropertyBlock', {
    custom_parameter_names: ['clock', 'reveal', 'style'],
    custom_parameter_values: [
      [elapsed, elapsed * 0.5, 0, 0],
      reveal,
      [cur.style, 0, 0, 0],
    ],
  });
}

// setComponent replaces the whole component, so every Text field must be resent.
interface TextStyle { size: number; color: number[]; align: string; valign: string; overflow: string; }
const TEXT_STYLE: Record<string, TextStyle> = {
  badge: { size: 30, color: [1.0, 0.78, 0.36, 1], align: 'Left', valign: 'Middle', overflow: 'Overflow' },
  code: { size: 21, color: [0.6, 0.9, 0.75, 1], align: 'Left', valign: 'Top', overflow: 'Overflow' },
  cn: { size: 34, color: [1, 1, 1, 0.96], align: 'Center', valign: 'Middle', overflow: 'Overflow' },
  en: { size: 24, color: [0.8, 0.86, 0.92, 0.9], align: 'Center', valign: 'Middle', overflow: 'Overflow' },
  mode: { size: 26, color: [0.45, 0.85, 0.95, 1], align: 'Right', valign: 'Middle', overflow: 'Overflow' },
};

function setText(name: string, text: string): void {
  const id = ui[name];
  const style = TEXT_STYLE[name];
  if (id === undefined || style === undefined) return;
  setComponent(id, 'Text', {
    text, font: 'Assets/Fonts/NotoSansSC.ttf', font_size: style.size, color: style.color,
    alignment: style.align, vertical_align: style.valign, line_spacing: 1.15,
    horizontal_overflow: style.overflow, vertical_overflow: style.overflow, raycast_target: false,
  });
}

function onSceneLoaded(_scene: EngineSceneInfo): void {
  for (const e of engine.snapshot.entities) {
    if (!e.name) continue;
    byName[e.name] = e.entity;
  }
  pollenId = byName['Pollen'] ?? -1;
  cameraId = byName['Main Camera'] ?? -1;
  envId = byName['Environment'] ?? -1;
  for (const key of ['Water', 'Island']) if (byName[key]) stylable.push(byName[key]);
  for (const name in byName) if (/^Rock /.test(name)) stylable.push(byName[name]);
  ui = {
    badge: byName['panel-badge'], code: byName['panel-code'],
    cn: byName['subtitle-cn'], en: byName['subtitle-en'], mode: byName['mode'],
    fill: byName['progress-fill'],
  };
  if (pollenId > 0) engine.setActive(pollenId, false);
  applyStageText(true);
}

function applyStageText(force: boolean): void {
  const s = STAGES[stage];
  setText('badge', s.badge);
  setText('code', s.code);
  setText('cn', s.cn);
  setText('en', s.en);
  setText('mode', STYLE_NAMES[Math.round(cur.style)]);
}

function pressed(key: string): boolean {
  return engine.input.pressedKeys.indexOf(key) >= 0;
}

function setStage(next: number): void {
  stage = Math.max(0, Math.min(STAGES.length - 1, next));
  stageTimer = 0;
  applyStageText(false);
}

function onTick(dt: number, _frame: number): void {
  elapsed += dt;
  stageTimer += dt;

  // ----- input
  if (pressed('Space')) setStage(stage + 1);
  if (pressed('KeyR')) { setStage(0); styleTarget = 0; autoplay = true; }
  if (pressed('Tab')) autoplay = !autoplay;
  if (pressed('Digit1')) styleTarget = 0;
  if (pressed('Digit2')) styleTarget = 1;
  if (pressed('Digit3')) styleTarget = 2;
  if (autoplay && stageTimer > 7.5 && stage < STAGES.length - 1) setStage(stage + 1);

  const s = STAGES[stage];

  // ----- smooth reveal interpolation
  const k = 1 - Math.pow(0.0025, dt); // frame-rate independent easing
  const target = s.water;
  cur.water = [lerp(cur.water[0], target[0], k), lerp(cur.water[1], target[1], k),
    lerp(cur.water[2], target[2], k), lerp(cur.water[3], target[3], k)];
  const g = s.ground;
  cur.ground = [lerp(cur.ground[0], g[0], k), lerp(cur.ground[1], g[1], k), g[2], g[3]];
  const sk = s.sky;
  cur.sky = [lerp(cur.sky[0], sk[0], k), lerp(cur.sky[1], sk[1], k), elapsed * 0.02, 0];
  cur.style = lerp(cur.style, styleTarget, k);
  cur.exposure = lerp(cur.exposure, s.exposure, k);
  cur.camRadius = lerp(cur.camRadius, s.camRadius, k);
  cur.camHeight = lerp(cur.camHeight, s.camHeight, k);
  cur.camAngle += dt * 0.06;

  // ----- push shader parameters (water + island + rocks share clock/reveal/style)
  for (const id of stylable) {
    pushMaterial(id, id === byName['Water'] ? cur.water : cur.ground);
  }

  // ----- environment: swap the baked sky (clear -> cloud-rich) at the cloud stage,
  // and ramp exposure. The env map also drives the water/rock reflections.
  const wantClouds = !!s.dome;
  const cloudTex = wantClouds ? 'Assets/Textures/sky-clouds.png' : 'Assets/Textures/sky-clear.png';
  if (envId > 0 && (Math.abs(cur.exposure - lastEnvExposure) > 0.004 || cloudTex !== lastEnvTex)) {
    lastEnvExposure = cur.exposure;
    lastEnvTex = cloudTex;
    setComponent(envId, 'EnvironmentLight', {
      sky_color: [0.05, 0.16, 0.36, 1], equator_color: [0.9, 0.42, 0.2, 1],
      ground_color: [0.02, 0.03, 0.05, 1], diffuse_intensity: 0.7,
      specular_intensity: 1.0, texture: cloudTex,
      background_enabled: true, background_intensity: 1.0,
      exposure: cur.exposure, tone_mapping: true,
    });
  }
  if (pollenId > 0) engine.setActive(pollenId, s.pollen);

  // ----- cinematic orbit camera
  if (cameraId > 0) {
    const r = cur.camRadius;
    const eye = [Math.sin(cur.camAngle) * r, cur.camHeight, Math.cos(cur.camAngle) * r];
    const targetPos = [0, 52, 0];
    setComponent(cameraId, 'Transform', {
      position: eye, rotation: lookAt(eye, targetPos), scale: [1, 1, 1],
    });
  }

  // ----- progress bar (fills across the whole sequence)
  if (ui.fill !== undefined) {
    const frac = (stage + Math.min(1, stageTimer / 7.5)) / STAGES.length;
    setComponent(ui.fill, 'RectTransform', {
      anchor_min: [0.5, 0.5], anchor_max: [0.5, 0.5], pivot: [0, 0.5],
      anchored_position: [-960, -534], size_delta: [1920 * Math.min(1, frac), 8],
    });
  }

  if (Math.floor(elapsed * 2) % 2 === 0) applyStageText(false);
}
