"""Author: MiYu. Preserve pinned reciprocal interpolation coefficients for native CReal.

Development-only generation from the user-provided reference binary. Runtime
uses the checked-in numeric constants and never reads or loads Game.dll.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / 'tmp/docs-artifacts/frost-siege-engine/dependencies'))
import pefile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--data-root', type=Path, default=Path('E:/Program Files (x86)/dzclient/Game/Warcraft III Frozen Throne'))
parser.add_argument('--output', type=Path, default=ROOT / 'watcher/war3/src/jass_reciprocal.inc')
args = parser.parse_args()
profile = json.loads((ROOT / 'watcher/war3/profiles/classic-1.27.json').read_text(encoding='utf-8-sig'))
raw = (args.data_root / 'Game.dll').read_bytes()
digest = hashlib.sha256(raw).hexdigest()
assert digest == profile['referenceGame']['sha256'], 'Coefficient RVA requires pinned Game.dll'
image = pefile.PE(data=raw)
assert image.OPTIONAL_HEADER.ImageBase == 0x6f000000 and image.FILE_HEADER.Machine == 0x14c
data = image.get_data(0x952fc0, 1025 * 4)
assert len(data) == 4100
values = struct.unpack('<1025I', data)
assert values[0] == 0x800000 and values[-1] == 0
assert all(a >= b for a, b in zip(values, values[1:]))
lines = ['// Author: MiYu. Original 1.27 reciprocal interpolation coefficients.',
         f'// Source: user-provided Game.dll SHA-256 {digest}, RVA 0x952fc0.',
         f'// Table SHA-256 {hashlib.sha256(data).hexdigest()}; generated by generate_jass_reciprocal.py.']
lines += ['    ' + ','.join(f'0x{value:08x}u' for value in values[at:at + 8]) + ',' for at in range(0, len(values), 8)]
args.output.parent.mkdir(parents=True, exist_ok=True)
args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
print(json.dumps(dict(entries=len(values), tableSha256=hashlib.sha256(data).hexdigest(), output=str(args.output))))
